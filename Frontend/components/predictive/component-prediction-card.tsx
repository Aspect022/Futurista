"use client"

import { useState } from "react"
import { Sparkles, Share2, Check, AlertTriangle } from "lucide-react"
import Link from "next/link"

type Risk = "Normal" | "Low" | "Medium" | "High" | "Critical"

interface ActionInfo {
  message: string
  cost: string
  buttonLabel: string
  buttonVariant: "critical" | "high" | "medium"
  nearestCenter?: string
}

const ACTION_MAP: Record<Risk, ActionInfo | null> = {
  Critical: {
    message: "Stop driving long distances immediately",
    cost: "Estimated repair cost: ₹1,800 – ₹3,500",
    buttonLabel: "Book Emergency Check",
    buttonVariant: "critical",
    nearestCenter: "Nearest service centre: 2.3 km away",
  },
  High: {
    message: "Book a service within the next 2 weeks",
    cost: "Estimated repair cost: ₹800 – ₹2,000",
    buttonLabel: "Book a Mechanic",
    buttonVariant: "high",
  },
  Medium: {
    message: "Keep an eye on this at your next regular service",
    cost: "Estimated repair cost: ₹300 – ₹900",
    buttonLabel: "Add to Service List",
    buttonVariant: "medium",
  },
  Low: null,
  Normal: null,
}

const buttonClasses: Record<string, string> = {
  critical: "bg-red-600 hover:bg-red-700 text-white",
  high: "bg-amber-500 hover:bg-amber-600 text-white",
  medium: "bg-muted hover:bg-muted/80 text-foreground",
}

export function ComponentPredictionCard({
  name,
  risk,
  daysToFailure,
  confidence,
  trend,
  onExplain,
}: {
  name: string
  risk: Risk
  daysToFailure: number
  confidence: number
  trend: number[]
  onExplain?: () => void
}) {
  const [copied, setCopied] = useState(false)

  const riskBadgeClasses: Record<Risk, string> = {
    Normal:   "text-muted-foreground border-border bg-muted",
    Low:      "text-muted-foreground border-border bg-muted",
    Medium:   "text-amber-700 dark:text-amber-300 border-amber-200 dark:border-amber-800 bg-amber-50 dark:bg-amber-900/20",
    High:     "text-amber-800 dark:text-amber-200 border-amber-300 dark:border-amber-700 bg-amber-100 dark:bg-amber-900/30",
    Critical: "text-red-700 dark:text-red-300 border-red-300 dark:border-red-700 bg-red-50 dark:bg-red-900/20",
  }

  const points = trend
    .map((v, i) => `${(i / (trend.length - 1)) * 100},${100 - v}`)
    .join(" ")

  const actionInfo = ACTION_MAP[risk]

  const handleShareWithMechanic = async () => {
    const text = `Car: Toyota Innova 2021
Component: ${name}
Risk: ${risk}
Days to issue: ${daysToFailure} days
AI note: Needs inspection
Generated by Futurista AI`

    try {
      await navigator.clipboard.writeText(text)
    } catch {
      const textarea = document.createElement("textarea")
      textarea.value = text
      document.body.appendChild(textarea)
      textarea.select()
      document.execCommand("copy")
      document.body.removeChild(textarea)
    }
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  return (
    <div className="rounded-2xl border border-border bg-card text-card-foreground p-5 shadow-sm flex flex-col">
      {/* Header */}
      <div className="flex items-start justify-between gap-3">
        <div>
          <div className="text-sm font-medium text-foreground">{name}</div>
          <div className="mt-1 inline-flex items-center gap-2 flex-wrap">
            <span className={`rounded-md border px-2 py-0.5 text-xs font-medium ${riskBadgeClasses[risk]}`}>
              {risk}
            </span>
            <span className="text-xs text-muted-foreground">{daysToFailure} days</span>
            <span className="text-xs text-muted-foreground">{confidence}% sure</span>
          </div>
        </div>
      </div>

      {/* Sparkline */}
      <div className="mt-4 h-16 w-full">
        <svg viewBox="0 0 100 100" preserveAspectRatio="none" className="h-full w-full">
          <polyline
            fill="none"
            stroke="currentColor"
            className="text-foreground"
            strokeWidth="2"
            points={points}
          />
          <line x1="0" y1="100" x2="100" y2="100" stroke="currentColor" className="text-border" strokeWidth="0.5" />
          <line x1="0" y1="75"  x2="100" y2="75"  stroke="currentColor" className="text-border/50" strokeWidth="0.5" />
          <line x1="0" y1="50"  x2="100" y2="50"  stroke="currentColor" className="text-border/50" strokeWidth="0.5" />
          <line x1="0" y1="25"  x2="100" y2="25"  stroke="currentColor" className="text-border/50" strokeWidth="0.5" />
        </svg>
      </div>

      {/* Action info */}
      {actionInfo ? (
        <div className="mt-4 p-3 rounded-lg bg-muted/60 border border-border space-y-1.5">
          <div className="flex items-start gap-2">
            <AlertTriangle className="h-4 w-4 text-amber-500 mt-0.5 flex-shrink-0" />
            <p className="text-xs font-medium text-foreground">{actionInfo.message}</p>
          </div>
          <p className="text-xs text-muted-foreground">{actionInfo.cost}</p>
          {actionInfo.nearestCenter && (
            <p className="text-xs text-muted-foreground">{actionInfo.nearestCenter}</p>
          )}
        </div>
      ) : (
        <div className="mt-4 p-3 rounded-lg bg-green-50 dark:bg-green-900/20 border border-green-200 dark:border-green-800">
          <p className="text-xs text-green-700 dark:text-green-300 font-medium">
            ✅ All good — check again at your next service
          </p>
        </div>
      )}

      {/* CTA row */}
      <div className="mt-3 flex gap-2">
        {actionInfo ? (
          <Link href="/appointment-booking" className="flex-1">
            <button
              className={`w-full rounded-lg py-2 text-sm font-medium transition-colors ${buttonClasses[actionInfo.buttonVariant]}`}
            >
              {actionInfo.buttonLabel}
            </button>
          </Link>
        ) : (
          <Link href="/appointment-booking" className="flex-1">
            <button className="w-full rounded-lg bg-primary hover:bg-primary/90 text-primary-foreground py-2 text-sm font-medium transition-colors">
              Book a Mechanic
            </button>
          </Link>
        )}
        <button
          onClick={onExplain}
          className="flex items-center justify-center gap-1 rounded-lg border border-border bg-card hover:bg-muted px-3 py-2 text-sm font-medium transition-colors text-indigo-500 dark:text-indigo-400"
        >
          <Sparkles className="h-4 w-4" />
          Explain
        </button>
      </div>

      {/* Share with Mechanic */}
      <button
        onClick={handleShareWithMechanic}
        className="mt-2 w-full flex items-center justify-center gap-2 py-2 rounded-lg border border-dashed border-border text-xs text-muted-foreground hover:bg-muted hover:text-foreground transition-colors"
      >
        {copied ? (
          <>
            <Check className="h-3.5 w-3.5 text-green-500" />
            <span className="text-green-600 dark:text-green-400 font-medium">Copied!</span>
          </>
        ) : (
          <>
            <Share2 className="h-3.5 w-3.5" />
            Share with Mechanic
          </>
        )}
      </button>
    </div>
  )
}
